#!/bin/bash

# =====================================================================
# 🛠️ سكربت التعديلات السريعة - الحوباني V5.2
# =====================================================================

echo "🔧 بدء تطبيق التعديلات..."

# ============================================================
# 1. عمل نسخ احتياطية
# ============================================================
echo "📁 عمل نسخ احتياطية..."
cp main.py main.py.backup
cp advisor_core.py advisor_core.py.backup
cp intent.py intent.py.backup
cp conversation_engine.py conversation_engine.py.backup

# ============================================================
# 2. تحديث intent.py - إضافة about_identity
# ============================================================
echo "📝 تحديث intent.py..."

# إضافة about_identity إلى valid_intents
sed -i "s/'execution_request', 'general'/'execution_request', 'about_identity', 'general'/g" intent.py

# إضافة about_identity إلى system_prompt
sed -i "/- execution_request: طلب تنفيذ صفقة/a\\        - about_identity: سؤال عن هوية البوت ومن صنعه واسمه" intent.py

# إضافة الكلمات المفتاحية في _fallback_classify
sed -i "/# البوت نفسه/i\\        # ============================================================\n        # هوية البوت (جديد)\n        # ============================================================\n        if any(w in text for w in ['من انت', 'من أنت', 'ما اسمك', 'عرفني', 'مين انت', 'who are you', 'your name', 'هو انت', 'من صنعك', 'مين مطورك']):\n            return 'about_identity'\n" intent.py

# ============================================================
# 3. تحديث advisor_core.py - دمج intents_library
# ============================================================
echo "📝 تحديث advisor_core.py..."

# إضافة الاستيراد
sed -i "1i from intents_library import get_response, is_dynamic, get_handler" advisor_core.py

# ============================================================
# 4. تحديث conversation_engine.py - تحسين الردود
# ============================================================
echo "📝 تحديث conversation_engine.py..."

# إضافة تعليمات الاعتراف بالجهل
sed -i "/تعليمات الاستجابة:/a\\        11. إذا لم تفهم السؤال، اعترف بذلك واطلب توضيحاً بأسلوب مهذب" conversation_engine.py

# ============================================================
# 5. تحديث persona.py - توحيد الاسم
# ============================================================
echo "📝 تحديث persona.py..."

# استبدال حُباني بالحوباني
sed -i 's/حُباني/الحوباني/g' persona.py

# ============================================================
# 6. تحديث main.py - تحسين معالجة الأخطاء
# ============================================================
echo "📝 تحديث main.py..."

# تعديل analyze_and_send لإرسال رسالة فقط عند الطلب اليدوي
sed -i '/if not data_15m:/,/return/ s/send_telegram_message("⚠️ عذراً، لم أتمكن من جلب بيانات السوق حالياً. يرجى المحاولة لاحقاً.")/if is_manual:\n            send_telegram_message("⚠️ عذراً، لم أتمكن من جلب بيانات السوق حالياً. يرجى المحاولة لاحقاً.")/' main.py

# ============================================================
# 7. إنشاء intents_library.py (إذا لم يكن موجوداً)
# ============================================================
if [ ! -f "intents_library.py" ]; then
    echo "📄 إنشاء intents_library.py..."
    cat > intents_library.py << 'EOF'
# =====================================================================
# 📚 مكتبة النيات والردود - الحوباني V5.2
# =====================================================================

INTENTS_LIBRARY = {
    "about_identity": {
        "keywords": ["من انت", "من أنت", "ما اسمك", "عرفني", "مين انت"],
        "response": """
🤖 **أنا الحوباني - مستشارك المالي الذكي والصديق!**

صُنعت بواسطة المطور باسام حوباني (Bassam Hobany) لأكون:
• مستشاراً فنياً للنفط والفضة
• محللاً للصفقات والأسواق
• صديقاً يتعلم من أخطائك وأخطائه

📌 **دوري:** مستشار، ليس متداولاً. القرار النهائي لك.
"""
    }
}

def get_response(intent):
    if intent in INTENTS_LIBRARY:
        return INTENTS_LIBRARY[intent].get("response")
    return None

def is_dynamic(intent):
    return False

def get_handler(intent):
    return None
EOF
fi

# ============================================================
# 8. إضافة أزرار جديدة في main.py (send_main_menu)
# ============================================================
echo "📝 تحديث الأزرار..."

# استبدال keyboard بإضافة زر تحليل الصفقة الأخيرة
sed -i '/keyboard = \[/,/\]/c\
    keyboard = [\n        ["🛢️ تحليل النفط", "🥈 تحليل الفضة"],\n        ["🔍 وضع الصفقة الحالية", "📊 تقرير الأداء"],\n        ["💬 محادثة ذكية", "🔍 تحليل الصفقة الأخيرة"],\n        ["🧠 تقرير استخباراتي"]\n    ]' main.py

# ============================================================
# 9. تنظيف الملفات
# ============================================================
echo "🧹 تنظيف الملفات..."

# حذف الأسطر الفارغة المتكررة
find . -name "*.py" -exec sed -i '/^$/N;/^\n$/d' {} \;

# ============================================================
# ✅ الانتهاء
# ============================================================
echo ""
echo "✅ ✅ ✅ تم تطبيق جميع التعديلات بنجاح!"
echo ""
echo "📋 تم عمل نسخ احتياطية للملفات الأصلية:"
echo "   • main.py.backup"
echo "   • advisor_core.py.backup"
echo "   • intent.py.backup"
echo "   • conversation_engine.py.backup"
echo ""
echo "🚀 يمكنك الآن تشغيل البوت: python main.py"
