    @classmethod
    def get_mood_response(cls, mood: str, context: str = "") -> str:
        """
        الحصول على رد حسب مزاج السوق
        
        Args:
            mood: المزاج (bullish, bearish_warning, danger, neutral, encouragement, learning)
            context: سياق إضافي (اختياري)
        
        Returns:
            str: رد تولين
        """
        responses = cls.MOODS.get(mood, cls.MOODS["neutral"])
        return random.choice(responses)
    
    @classmethod
    def analyze_user_emotion(cls, text: str) -> str:
        """
        تحليل عاطفة المستخدم من النص
        
        Args:
            text: نص رسالة المستخدم
        
        Returns:
            str: العاطفة المكتشفة (fear, greedy, sad, happy, confident, frustration, neutral)
        """
        text_lower = text.lower()
        
        # قوائم الكلمات المفتاحية
        fear_words = [
            "خايف", "أخاف", "قلق", "متردد", "حذر", "خوف", "هلع", "توتر",
            "خائف", "قلقان", "مذعور", "مرعوب", "worried", "scared"
        ]
        greedy_words = [
            "مغامر", "جريء", "طمع", "أريد ربح", "سريع", "جشع",
            "متهور", "طماع", "ربح سريع", "greedy", "aggressive"
        ]
        sad_words = [
            "خسرت", "حزين", "فشل", "يأس", "محبط", "تعبت",
            "خسران", "حزنان", "مكتئب", "مكسور", "sad", "depressed"
        ]
        happy_words = [
            "ربحت", "سعيد", "فرحان", "نجحت", "مبسوط", "ممتاز",
            "فرحة", "سعادة", "نجاح", "happy", "great", "excellent"
        ]
        confident_words = [
            "واثق", "متأكد", "جاهز", "قوي", "مستعد",
            "واثق", "أكيد", "متيقن", "confident", "ready"
        ]
        frustration_words = [
            "زعلان", "ضيق", "مضيق", "متضايق", "زعل", "غضبان",
            "معصب", "غاضب", "frustrated", "angry", "upset"
        ]
        
        # تحديد العاطفة
        if any(w in text_lower for w in fear_words):
            return "fear"
        elif any(w in text_lower for w in greedy_words):
            return "greedy"
        elif any(w in text_lower for w in sad_words):
            return "sad"
        elif any(w in text_lower for w in happy_words):
            return "happy"
        elif any(w in text_lower for w in confident_words):
            return "confident"
        elif any(w in text_lower for w in frustration_words):
            return "frustration"
        else:
            return "neutral"
    
    @classmethod
    def respond_to_emotion(cls, emotion: str, context: str = "") -> str:
        """
        الرد على عاطفة المستخدم
        
        Args:
            emotion: العاطفة المكتشفة
            context: سياق إضافي (اختياري)
        
        Returns:
            str: رد تولين
        """
        responses = cls.EMOTION_RESPONSES.get(emotion, cls.EMOTION_RESPONSES["neutral"])
        return random.choice(responses)
    
